import assert from "node:assert/strict";
import { suggestProjectIntake, validateIntakeSuggestion, validateProjectResourceUrl } from "../lib/projects/project-intake";
const brief = "Review the website UI for every page and provide new designing recommendation for them.";
const suggested = suggestProjectIntake(brief);
assert.equal(suggested.title, "Website UI/UX Audit & Redesign Recommendations");
assert.equal(suggested.objective, brief);
assert.equal(suggested.source, "fallback");
assert.ok(suggested.resources.includes("website"));
const restaurant = suggestProjectIntake("Our vegan restaurant needs more customer acquisition");
assert.equal(restaurant.category, "business_growth");
assert.doesNotMatch(JSON.stringify(restaurant), /only vegan|verified|confirmed/i);
assert.equal(suggestProjectIntake("Produce an internal report from our dataset").category, "reporting");
assert.equal(suggestProjectIntake("Produce an internal report from our dataset").resources.includes("github"), false);
assert.equal(validateIntakeSuggestion({ title: "x" }, suggested), suggested);
assert.equal(validateIntakeSuggestion({ title: "Professional title", category: "bad/category", capabilities: ["UX", 3] }, suggested).category, suggested.category);
assert.equal(validateIntakeSuggestion({ title: "New title\nInjected" }, suggested), suggested);
for (const url of ["https://example.com", "https://github.com/company/repo", ""]) assert.equal(validateProjectResourceUrl(url), true);
for (const url of ["javascript:alert(1)", "file:///etc/passwd", "http://127.0.0.1", "http://169.254.169.254", "http://user:password@example.com", "http://172.20.0.1", "https://localhost", "https://[::1]"]) assert.equal(validateProjectResourceUrl(url), false);
console.log("Project intake: professional fallback naming, preserved original brief, configurable capabilities/resources, unverified classification, AI output validation and submitted URL checks passed.");
