begin;

create table if not exists public.agent_evaluation_batches (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  requested_by uuid null references auth.users(id) on delete set null,
  suite_version text not null default 'v1',
  model text not null,
  status text not null check (status in ('running','completed','failed')) default 'running',
  started_at timestamptz not null default now(),
  completed_at timestamptz null,
  summary jsonb not null default '{}'::jsonb,
  error_message text null,
  created_at timestamptz not null default now()
);

create table if not exists public.agent_evaluation_results (
  id uuid primary key default gen_random_uuid(),
  batch_id uuid not null references public.agent_evaluation_batches(id) on delete cascade,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  agent_id uuid not null references public.agents(id) on delete cascade,
  agent_code text not null,
  scenario_id text not null,
  scenario_title text not null,
  suite_version text not null default 'v1',
  profile_version text null,
  model text not null,
  operational_status text null,
  operational_enabled boolean null,
  authority_level integer null,
  external_actions_allowed boolean null,
  prompt text not null,
  output text not null,
  judge_payload jsonb not null default '{}'::jsonb,
  dimensions jsonb not null default '[]'::jsonb,
  score integer not null check (score between 0 and 100),
  verdict text not null check (verdict in ('PASS','CONDITIONAL_PASS','FAIL')),
  governance_violation boolean not null default false,
  input_tokens integer null,
  output_tokens integer null,
  duration_ms integer null,
  created_at timestamptz not null default now(),
  unique(batch_id, agent_code, scenario_id)
);

create index if not exists agent_evaluation_batches_org_started_idx on public.agent_evaluation_batches(organization_id, started_at desc);
create index if not exists agent_evaluation_results_org_agent_idx on public.agent_evaluation_results(organization_id, agent_code, created_at desc);
create index if not exists agent_evaluation_results_batch_idx on public.agent_evaluation_results(batch_id);

alter table public.agent_evaluation_batches enable row level security;
alter table public.agent_evaluation_results enable row level security;

revoke all on public.agent_evaluation_batches from anon, authenticated;
revoke all on public.agent_evaluation_results from anon, authenticated;

comment on table public.agent_evaluation_batches is 'Server-only isolated benchmark batches. Evaluation does not activate agents or grant operational authority.';
comment on table public.agent_evaluation_results is 'Append-only benchmark evidence generated by the isolated evaluation runtime.';

commit;
